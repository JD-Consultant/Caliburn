import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { compile } from "json-schema-to-typescript";
export const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const generated = [
  "generated/jd-editor-v2.schema.json",
  "types/jd-editor-v2.ts",
  "src/jd_editor_contract/models.py",
];
export async function generate(out = root) {
  const source = resolve(
    root,
    "../../../docs/specs/contracts/jd-editor-v2.schema.json",
  );
  for (const file of generated)
    await mkdir(dirname(resolve(out, file)), { recursive: true });
  await copyFile(source, resolve(out, generated[0]));
  const schema = JSON.parse(await readFile(source, "utf8"));
  let ts = await compile(schema, schema.title, {
    unreachableDefinitions: true,
    bannerComment:
      "/* Generated from docs/specs/contracts/jd-editor-v2.schema.json. Do not edit. */",
  });
  // The generator deduplicates pure $ref aliases. Preserve each public SSOT name mechanically.
  for (const [name, definition] of Object.entries(schema.$defs))
    if (
      definition.$ref &&
      !new RegExp(`export (?:type|interface) ${name}\\b`).test(ts)
    ) {
      const target = definition.$ref.split("/").at(-1);
      ts += `\nexport type ${name} = ${target};\n`;
    }
  await writeFile(resolve(out, generated[1]), ts);
  const result = spawnSync(
    "uv",
    [
      "run",
      "--project",
      root,
      "datamodel-codegen",
      "--input",
      source,
      "--input-file-type",
      "jsonschema",
      "--output",
      resolve(out, generated[2]),
      "--output-model-type",
      "pydantic_v2.BaseModel",
      "--target-python-version",
      "3.12",
      "--strict-types",
      "int",
      "--disable-timestamp",
      "--no-use-union-operator",
    ],
    { encoding: "utf8", env: { ...process.env, PYTHONUTF8: "1" } },
  );
  if (result.status !== 0)
    throw new Error(result.stderr || String(result.error));
  // The Python generator uses OS line endings; committed generated bytes use LF.
  const pythonOutput = resolve(out, generated[2]);
  await writeFile(pythonOutput, (await readFile(pythonOutput, "utf8")).replaceAll("\r\n", "\n"));
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await generate();
